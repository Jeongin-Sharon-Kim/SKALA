# ============================================================
# 1. Mini GPT Model
# ============================================================
#
# 역할:
# - Embedding
# - Transformer Block
# - Output Layer
#
# 을 연결하여 Language Model 구성
#
# ============================================================


class MiniGPT(nn.Module):

    def __init__(self, vocab_size, dim=64):
        super().__init__()

        # Token ID → Vector 변환

        self.token_embedding = nn.Embedding(vocab_size, dim)


        # Token 위치 정보 추가

        self.position_embedding = PositionalEncoding(dim)


        # Transformer Decoder Block

        self.block = TransformerBlock(dim)



        # Hidden Vector → Vocabulary Score 변환

        self.lm_head = nn.Linear(dim, vocab_size)



    def forward(self, x):

        # Token Embedding 생성
        token = self.token_embedding(x)


        # Position Embedding 생성
        position = self.position_embedding(x)


        # Token + Position 결합
        x = token + position


        # Transformer Block 통과
        x = self.block(x)


        # 다음 Token 확률 계산용 출력
        return self.lm_head(x)




# ============================================================
# 2. Model 생성 및 Optimizer 설정
# ============================================================


model = MiniGPT(vocab_size)


# Transformer 학습에 많이 사용하는 Optimizer
optimizer = torch.optim.Adam(model.parameters(), lr = 1e-3)


# ============================================================
# 3. Training Loop
# ============================================================
#
# 역할:
# - 입력 Token(x)을 이용하여
#   다음 Token(y)을 예측하도록 학습
#
# Loss:
# Cross Entropy
#
# ============================================================


for epoch in range(500):

    # Forward 실행

    logits = model(x.unsqueeze(0)) #이게 뭐야??



    # 예측 결과와 실제 Token 비교

    loss = F.cross_entropy(logits.view(-1, logits.shape[-1]), y)


    # Gradient 초기화

    optimizer.zero_grad()



    # Backpropagation

    loss.backward()


    # Parameter 업데이트

    optimizer.step()


    if epoch % 100 == 0:
        print(f"Epoch:{epoch}, Loss:{loss.item()}")

# ============================================================
# 4. Text Generation
# ============================================================
#
# 역할:
# - 학습된 GPT 모델로 다음 Token 반복 생성
#
# 과정:
#
# 입력:
# hello
#
# 예측:
# hello w
#
# 반복:
# hello world
#
# ============================================================


def generate(model, start, length=20):

    # 추론 모드 전환

    model.eval()


    # 시작 문장을 Token 변환

    tokens = torch.tensor(
        encode(start),
        dtype = torch.long).unsqueeze(0)

    # Token 반복 생성

    for _ in range(length):

        # 현재 Token 기반 다음 Token 예측

        logits = model(tokens)


        # 마지막 위치의 가장 높은 확률 Token 선택

        next_token = torch.argmax(logits[0, -1], dim = -1)


        # 예측 Token 추가

        tokens = torch.concat(
            [tokens, next_token.unsqueeze(0).unsqueeze(0)], # Corrected: Added an extra unsqueeze(0)-> 왜??
            dim = 1
            )


    # Token ID → Text 변환

    return decode(tokens[0].tolist())



# ============================================================
# 5. Generation Test
# ============================================================


result = generate(model, "hello")


print("\nGenerated Text")
print(result)

