text = """
hello world
hello ai
hello transformer
hello gpt
"""


# 데이터에 존재하는 모든 문자 추출
# GPT에서는 Vocabulary 생성 과정에 해당

chars = sorted(set(text)) #중복 없게 하기 위해서 set사용


# Vocabulary 크기

vocab_size = len(chars)


print("Vocabulary:", chars)
print("Vocabulary Size:", vocab_size)



# ============================================================
# 3. Character Tokenizer 구현
# ============================================================
#
# 역할:
# - 문자를 숫자 Token ID로 변환
# - Model은 문자열을 직접 처리하지 못하므로
#   숫자 형태의 입력 필요
#
# 예:
#
# "hello"
#
# ↓
#
# [7,4,8,8,9]
#
# ============================================================


# 문자 -> Token ID 변환 Dictionary

stoi = {ch : i for i, ch in enumerate(chars)} #이런 작성법 처음본다 이건뭐지??


# Token ID -> 문자 변환 Dictionary

itos = {i : ch for i, ch in enumerate(chars)}


# Encoding 함수
# 역할:
# 문자열을 Token ID 리스트로 변환

def encode(text):
    return [stoi[c] for c in text] #이것도 처음봄;;;;


# Decoding 함수
# 역할:
# Token ID 리스트를 원래 문자열로 복원

def decode(tokens):
    return "".join(itos[i] for i in tokens) #이것도 처음봐;;



# 전체 Text를 Token 데이터로 변환

data = torch.tensor(encode(text), dtype = torch.long)


print("\nEncoded Data")
print(data[:20])



