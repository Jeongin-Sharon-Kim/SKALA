# ============================================================
# 1. Positional Encoding
# ============================================================
#
# 역할:
# - Transformer는 Token 순서 정보를 알 수 없음
# - 위치 정보를 Embedding으로 추가
#
# 예:
#
# hello
# 0 1 2 3 4
#
# ============================================================


class PositionalEncoding(nn.Module):

    def __init__(self, dim, max_len=100):
        super().__init__()
        self.embedding = nn.Embedding(max_len, dim)


    def forward(self, x):
        #batch size, sequential lenth(?)
        B, T = x.shape
        positions = torch.arange(T, device = x.device)
        return self.embedding(positions)



# ============================================================
# 2. Masked Self Attention
# ============================================================
#
# 역할:
# - GPT 핵심 Attention 구조
# - 현재 Token은 이전 Token만 참고
#
# Causal Mask:
#
# 1 0 0
# 1 1 0
# 1 1 1
#
# 미래 Token 접근 차단
#
# ============================================================


class SelfAttention(nn.Module):

    def __init__(self, dim):
        super().__init__()
        self.qkv = nn.Linear(dim, dim * 3) #선형 레이어 변환(q,k,v 3개니까 3차원으로)
        self.output = nn.Linear(dim, dim) #아웃풋은 다시 1차원으로 해줘야하니까


    def forward(self, x):
        #batch size, sequential len, dim of embedding
        B, T, C = x.shape  #입력차원 받아서

        # Query, Key, Value 생성

        q, k, v = self.qkv(x).chunk(3, dim = -1) #마지막 차원 기준으로 등분 분할해서 qkv만들기


        # Query와 Key 기반 Attention Score 계산

        attention = q @ k.transpose(-2, -1) #골뱅이는 뭐지




        # 미래 Token 참조 방지 Mask 생성

        mask = torch.tril(torch.ones(T, T, device = x.device))


        attention = attention.masked_fill(mask == 0, float("-inf")) #-inf가 뭐임? 음의 무한대? 왜 하는건데?


        # Attention 확률 계산

        attention = F.softmax(attention, dim = -1)


        # Value와 Attention 결합

        return self.output(attention @ v)



# ============================================================
# 3. Transformer Decoder Block
# ============================================================
#
# 역할:
# - GPT Decoder Layer 구성
#
# 구조:
#
# LayerNorm
#    ↓
# Self Attention
#    ↓
# Residual
#    ↓
# Feed Forward
#    ↓
# Residual
#
# ============================================================


class TransformerBlock(nn.Module):

    def __init__(self, dim):
        super().__init__()

        # Self Attention Layer

        self.attention = SelfAttention(dim)

        # Normalization Layer

        self.norm1 = nn.LayerNorm(dim)


        # Feed Forward Network
        #
        # Transformer 내부 비선형 변환 담당

        # 첫번째 normalization
        # 은닉층에서 차원4배 확장 후 relu(비선형 활성화함수)로 다시 원래대로 만들기
        self.ffn = nn.Sequential(
            nn.Linear(dim, dim *4),
            nn.ReLU(),
            nn.Linear(dim *4, dim)

        )


        # 두 번째 Normalization

        self.norm2 = nn.LayerNorm(dim)



    def forward(self, x):

        # Attention + Residual Connection

        x = x + self.attention(self.norm1(x))


        # Feed Forward + Residual Connection

        x = x + self.ffn(self.norm2(x)) #ffn이 뭐지?

        return x

