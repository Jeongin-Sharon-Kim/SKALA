# PyTorch 기반 Neural Network 구현
import torch
import torch.nn as nn

# Loss 계산 및 Softmax 등 함수 사용
import torch.nn.functional as F



# ============================================================
# 2. Mini Dataset 생성
# ============================================================
#
# 실제 GPT는 대규모 Corpus를 사용하지만,
